package resort.board.dto;

public class HotelAvgDTO {

	private int h_code;
	private double hotelAvg;
	private int scoreCount;
	
	public int getH_code() {
		return h_code;
	}
	public void setH_code(int h_code) {
		this.h_code = h_code;
	}
	public double getHotelAvg() {
		return hotelAvg;
	}
	public void setHotelAvg(double hotelAvg) {
		this.hotelAvg = hotelAvg;
	}
	public int getScoreCount() {
		return scoreCount;
	}
	public void setScoreCount(int scoreCount) {
		this.scoreCount = scoreCount;
	}
	
	
}
